class PatchBuildException implements Exception {
  final String code;
  const PatchBuildException(this.code);
  @override
  String toString() => 'Patch build: $code';
}

void checkPatchCancellation(CancelToken cancellation) {
  if (cancellation.isCancelled) throw const PatchBuildException('cancelled');
}

class _HashSink implements Sink<Digest> {
  Digest? digest;
  @override
  void add(Digest value) => digest = value;
  @override
  void close() {}
}

/// Hashes the exact raw member/resource/result, not its containing archive.
Future<({int size, Map<String, String> hashes})> fingerprintPatchBytes(
    Stream<List<int>> bytes, CancelToken cancellation,
    {Map<String, String> expected = const {}, int? expectedSize}) async {
  final results = {
    for (final name in const ['md5', 'sha1', 'sha256']) name: _HashSink()
  };
  final sinks = {
    'md5': md5.startChunkedConversion(results['md5']!),
    'sha1': sha1.startChunkedConversion(results['sha1']!),
    'sha256': sha256.startChunkedConversion(results['sha256']!),
  };
  var size = 0;
  var crc = 0;
  try {
    checkPatchCancellation(cancellation);
    await for (final chunk in bytes) {
      checkPatchCancellation(cancellation);
      size += chunk.length;
      crc = getCrc32(chunk, crc);
      if (expectedSize != null && size > expectedSize) {
        throw const PatchBuildException('input_size_mismatch');
      }
      for (final sink in sinks.values) {
        sink.add(chunk);
      }
    }
  } finally {
    for (final sink in sinks.values) {
      sink.close();
    }
  }
  checkPatchCancellation(cancellation);
  final hashes = {
    'crc32': crc.toRadixString(16).padLeft(8, '0'),
    for (final entry in results.entries)
      entry.key: entry.value.digest!.toString()
  };
  if ((expectedSize != null && size != expectedSize) ||
      expected.entries
          .any((entry) => hashes[entry.key] != entry.value.toLowerCase())) {
    throw const PatchBuildException('input_fingerprint_mismatch');
  }
  return (size: size, hashes: Map<String, String>.unmodifiable(hashes));
}

/// Generated bytes enter the existing exact-file journal/native publication
/// lane. No fabricated Drive object, overwrite rename or filename adoption.
class PatchBuildPublication {
  final TransferJournal journal;
  final OwnedStorage storage;
  PatchBuildPublication(this.journal, {this.storage = const OwnedStorage()});

  Future<TransferRecord> publish(
      {required String buildId,
      required RemoteArtifact artifact,
      required File output,
      required String targetRoot,
      required String filename,
      required CancelToken cancellation}) async {
    // Reservation already coordinates this target with removal. Complete it
    // before entering publication's mutation; InstallationMutations is not
    // reentrant and journal.create acquires that same target internally.
    checkPatchCancellation(cancellation);
    final id = 'patch-$buildId';
    if (await journal.transfer(id) == null) {
      final plan = await storage.prepare(targetRoot);
      await journal.create(TransferRecord(
          id: id,
          artifact: artifact,
          destinationRoot: targetRoot,
          relativePath: filename,
          stagePath: plan.stagePath(id)));
    }
    final result = await InstallationMutations.run(
        p.join(targetRoot, filename),
        () => _publish(
            buildId, artifact, output, targetRoot, filename, cancellation));
    return retireCommittedStage(journal, storage, result);
  }

  Future<TransferRecord> _publish(
      String buildId,
      RemoteArtifact artifact,
      File output,
      String root,
      String filename,
      CancelToken cancellation) async {
    checkPatchCancellation(cancellation);
    final id = 'patch-$buildId';
    var record = (await journal.transfer(id))!;
    if (record.artifact.id != artifact.id ||
        record.artifact.providerChecksums['sha256'] !=
            artifact.providerChecksums['sha256'] ||
        record.destinationRoot != root ||
        record.relativePath != filename) {
      throw const PatchBuildException('publication_identity_changed');
    }
    if (record.lifecycle == TransferLifecycle.completed) {
      await InstallationIndex(journal, storage: storage).requireInstallation(
          record,
          await journal.installationForTarget(
              destinationRoot: root, relativePath: filename));
      return record;
    }
    OwnedStorageSession? session;
    Future<void> save(TransferRecord next) async {
      record = await journal.save(next);
    }

    Future<void> verify(Stream<Uint8List> bytes) async {
      await fingerprintPatchBytes(bytes, cancellation,
          expectedSize: artifact.sizeBytes,
          expected: artifact.providerChecksums);
    }

    try {
      if (record.publication == null) {
        await save(record.copyWith(
            lifecycle: TransferLifecycle.transferring, clearErrorCode: true));
        session = await storage.open(
            destinationRoot: root,
            relativePath: filename,
            stagePath: record.stagePath,
            durableOffset: record.durableOffset,
            expectedIdentity: record.stageIdentity);
        if (record.stageIdentity != null) {
          record = await journal.resumeStageCheckpoint(
              record, session.openedIdentity);
        } else {
          await save(record.copyWith(stageIdentity: session.openedIdentity));
        }
        var offset = record.durableOffset;
        var savedOffset = offset;
        await for (final chunk in output.openRead(offset)) {
          checkPatchCancellation(cancellation);
          for (var start = 0; start < chunk.length;) {
            final end =
                (start + OwnedStorage.maxChunkBytes).clamp(0, chunk.length);
            await session.write(
                offset, Uint8List.fromList(chunk.sublist(start, end)));
            offset += end - start;
            start = end;
          }
          if (offset - savedOffset >= 1024 * 1024) {
            await save(record.copyWith(
                durableOffset: offset,
                stageIdentity: await session.checkpoint()));
            savedOffset = offset;
          }
        }
        final identity = await session.checkpoint();
        await save(
            record.copyWith(durableOffset: offset, stageIdentity: identity));
        await save(record.copyWith(lifecycle: TransferLifecycle.verifying));
        await verify(session.bytes(offset));
        if (!(await session.checkpoint()).matches(identity)) {
          throw const PatchBuildException('output_changed');
        }
        await save(
            record.copyWith(verifiedChecksums: artifact.providerChecksums));
        await save(record.copyWith(
            lifecycle: TransferLifecycle.publishing,
            publication: TransferPublication(
                method: PublicationMethod.rename, sourceIdentity: identity)));
      } else {
        if (record.lifecycle != TransferLifecycle.publishing) {
          await save(record.copyWith(
              lifecycle: TransferLifecycle.publishing, clearErrorCode: true));
        }
        final stage = await storage.inspect(
            destinationRoot: root,
            relativePath: filename,
            stagePath: record.stagePath);
        final moved = stage == null &&
            record.publication!.method == PublicationMethod.rename;
        session = await storage.open(
            destinationRoot: root,
            relativePath: filename,
            stagePath: record.stagePath,
            durableOffset: record.durableOffset,
            expectedIdentity: record.publication!.sourceIdentity,
            published: moved);
        await verify(session.bytes(record.durableOffset));
        if (moved && !record.publication!.confirmed) {
          await save(record.copyWith(
              publication: TransferPublication(
                  method: PublicationMethod.rename,
                  sourceIdentity: record.publication!.sourceIdentity,
                  destinationIdentity: await session.checkpoint(),
                  confirmed: true)));
        }
      }
      checkPatchCancellation(cancellation);
      if (!record.publication!.confirmed &&
          record.publication!.method == PublicationMethod.rename) {
        try {
          final identity =
              await session.publish(record.publication!.sourceIdentity);
          await save(record.copyWith(
              publication: TransferPublication(
                  method: PublicationMethod.rename,
                  sourceIdentity: record.publication!.sourceIdentity,
                  destinationIdentity: identity,
                  confirmed: true)));
        } on OwnedStorageException catch (error) {
          if (!{'unsupported', 'cross_volume'}.contains(error.code)) rethrow;
          await save(record.copyWith(
              publication: TransferPublication(
                  method: PublicationMethod.copy,
                  sourceIdentity: record.publication!.sourceIdentity)));
        }
      }
      if (!record.publication!.confirmed) {
        final intent = record.publication!;
        final copy = await session.beginPublicationCopy(intent.sourceIdentity,
            durableOffset: intent.copiedOffset,
            destinationIdentity: intent.destinationIdentity);
        Future<void> checkpoint(
            {bool confirmed = false, NativeFileIdentity? identity}) async {
          final value = identity ?? await copy.checkpoint();
          await save(record.copyWith(
              publication: TransferPublication(
                  method: PublicationMethod.copy,
                  sourceIdentity: intent.sourceIdentity,
                  destinationIdentity: value,
                  confirmed: confirmed)));
        }

        if (intent.destinationIdentity == null) {
          await checkpoint(identity: copy.openedIdentity);
        }
        await copy.validateResumePrefix(
            checkCancellation: () => checkPatchCancellation(cancellation));
        var saved = copy.copiedBytes;
        while (copy.copiedBytes < record.durableOffset) {
          checkPatchCancellation(cancellation);
          await copy.copyNext((record.durableOffset - copy.copiedBytes)
              .clamp(0, OwnedStorage.maxChunkBytes));
          if (copy.copiedBytes - saved >= 1024 * 1024) {
            await checkpoint();
            saved = copy.copiedBytes;
          }
        }
        await checkpoint();
        await verify(copy.bytes());
        await checkpoint(
            confirmed: true,
            identity:
                await copy.finish(record.publication!.destinationIdentity!));
      }
      checkPatchCancellation(cancellation);
      final destination = record.publication!.destinationIdentity!;
      final current = await storage.inspect(
          destinationRoot: root,
          relativePath: filename,
          stagePath: record.stagePath,
          published: true);
      if (current == null || !current.matches(destination)) {
        throw const PatchBuildException('output_changed');
      }
      // A close failure leaves the publication intent recoverable, not installed.
      await session.close();
      session = null;
      return await journal.complete(
          record,
          InstalledArtifact(
              id: record.id,
              transferId: record.id,
              artifact: artifact,
              destinationRoot: root,
              relativePath: filename,
              sizeBytes: artifact.sizeBytes!,
              verifiedChecksums: record.verifiedChecksums,
              fileIdentity: destination),
          checkCancellation: () => checkPatchCancellation(cancellation));
    } catch (error) {
      if (record.lifecycle != TransferLifecycle.completed) {
        if (record.publication == null && session != null) {
          final identity = await session.checkpoint();
          await save(record.copyWith(
              durableOffset: identity.sizeBytes, stageIdentity: identity));
        }
        await save(record.copyWith(
            lifecycle: cancellation.isCancelled
                ? TransferLifecycle.paused
                : TransferLifecycle.failed,
            errorCode: cancellation.isCancelled
                ? 'cancelled'
                : 'patch_publication_failed'));
      }
      rethrow;
    } finally {
      await session?.close();
    }
  }
}
